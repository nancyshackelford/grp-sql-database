        ON DELETE CASCADE,

    database text NOT NULL,

    projectid integer,

    artifact_type text NOT NULL,

    artifact_subtype text,

    file_name text,

    file_extension text,

    file_path_or_storage_key text,

    storage_bucket text,

    file_hash text,

    source_layer text,

    workflow_stage text,

    created_by text,

